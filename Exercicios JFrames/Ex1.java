    private void BotaoFazContaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotaoFazContaActionPerformed
        // TODO add your handling code here:
        String strNum1 = entradaXX.getText();
        String strNum2 = entradaX.getText();
        String strNum3 = entradaSozinho.getText();
        
        int A = Integer.parseInt(strNum1);
        int B = Integer.parseInt(strNum2);
        int C = Integer.parseInt(strNum3);
        
        double delta = Math.pow(B,2)-(4*A*C);
        double raiz1 = (-B + Math.sqrt(delta))/(2*A);
        double raiz2 = (-B - Math.sqrt(delta))/(2*A);
        
        String strRaiz1 = String.valueOf(raiz1);
        String strRaiz2 = String.valueOf(raiz2);
        saidaRaiz1.setText(strRaiz1);
        saidaRaiz2.setText(strRaiz2);
    }//GEN-LAST:event_BotaoFazContaActionPerformed

